#!/usr/bin/env bash
#
# Idempotent bootstrap for the IUVENTA WordPress development environment.
#
# Safe to run repeatedly: every step checks current state before acting.
# Requires: php (cli) and wp-cli (`wp`) available on PATH.
#
#   - Downloads WordPress core into ./wp
#   - Installs the SQLite database integration plugin + db.php drop-in
#   - Generates ./wp/wp-config.php (SQLite, wp-content kept in repo root)
#   - Installs WordPress and activates the "iuventa" theme
#
# This script does NOT start the web server. Use bin/serve.sh for that.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

WP_DIR="$ROOT/wp"
CONTENT_DIR="$ROOT/wp-content"
PLUGIN_DIR="$CONTENT_DIR/plugins/sqlite-database-integration"
WP_LOCALE="${WP_LOCALE:-ru_RU}"
SITE_URL="${WP_HOME:-http://localhost:8080}"

WP_BIN="${WP_BIN:-wp}"
if ! command -v "$WP_BIN" >/dev/null 2>&1; then
	echo "ERROR: wp-cli ('$WP_BIN') not found on PATH. Install it before running setup." >&2
	exit 1
fi
WP="$WP_BIN --path=$WP_DIR --allow-root"

echo "==> IUVENTA setup (root: $ROOT)"

# 1. WordPress core ----------------------------------------------------------
if [ ! -f "$WP_DIR/wp-load.php" ]; then
	echo "==> Downloading WordPress core ($WP_LOCALE)..."
	mkdir -p "$WP_DIR"
	$WP_BIN core download --path="$WP_DIR" --locale="$WP_LOCALE" --allow-root
else
	echo "==> WordPress core already present."
fi

# 2. SQLite integration plugin -----------------------------------------------
mkdir -p "$CONTENT_DIR/plugins"
if [ ! -f "$PLUGIN_DIR/load.php" ]; then
	echo "==> Installing sqlite-database-integration plugin..."
	tmp_zip="$(mktemp /tmp/sqlite-XXXXXX.zip)"
	curl -fsSL "https://downloads.wordpress.org/plugin/sqlite-database-integration.latest-stable.zip" -o "$tmp_zip"
	unzip -q -o "$tmp_zip" -d "$CONTENT_DIR/plugins/"
	rm -f "$tmp_zip"
else
	echo "==> SQLite plugin already present."
fi

# 3. db.php drop-in ----------------------------------------------------------
if [ ! -f "$CONTENT_DIR/db.php" ]; then
	echo "==> Creating wp-content/db.php drop-in..."
	sed -e "s#{SQLITE_IMPLEMENTATION_FOLDER_PATH}#$PLUGIN_DIR#g" \
		-e "s#{SQLITE_PLUGIN}#sqlite-database-integration/load.php#g" \
		"$PLUGIN_DIR/db.copy" > "$CONTENT_DIR/db.php"
else
	echo "==> db.php drop-in already present."
fi

# 4. wp-config.php -----------------------------------------------------------
if [ ! -f "$WP_DIR/wp-config.php" ]; then
	echo "==> Generating wp/wp-config.php..."
	cat > "$WP_DIR/wp-config.php" <<'PHP'
<?php
/**
 * WordPress configuration for the IUVENTA project (local development).
 * Generated by bin/setup.sh — SQLite database, wp-content kept in repo root.
 */
if ( ! defined( 'WP_HOME' ) ) {
	define( 'WP_HOME', getenv( 'WP_HOME' ) ?: 'http://localhost:8080' );
}
if ( ! defined( 'WP_SITEURL' ) ) {
	define( 'WP_SITEURL', WP_HOME . '/wp' );
}
define( 'WP_CONTENT_DIR', dirname( __DIR__ ) . '/wp-content' );
define( 'WP_CONTENT_URL', WP_HOME . '/wp-content' );
define( 'DB_NAME', 'wordpress' );
define( 'DB_USER', 'root' );
define( 'DB_PASSWORD', '' );
define( 'DB_HOST', 'localhost' );
define( 'DB_CHARSET', 'utf8' );
define( 'DB_COLLATE', '' );
$table_prefix = 'wp_';
define( 'AUTH_KEY',         'iuventa-local-auth-key' );
define( 'SECURE_AUTH_KEY',  'iuventa-local-secure-auth-key' );
define( 'LOGGED_IN_KEY',    'iuventa-local-logged-in-key' );
define( 'NONCE_KEY',        'iuventa-local-nonce-key' );
define( 'AUTH_SALT',        'iuventa-local-auth-salt' );
define( 'SECURE_AUTH_SALT', 'iuventa-local-secure-auth-salt' );
define( 'LOGGED_IN_SALT',   'iuventa-local-logged-in-salt' );
define( 'NONCE_SALT',       'iuventa-local-nonce-salt' );
define( 'WP_DEBUG', true );
define( 'WP_DEBUG_LOG', true );
define( 'WP_DEBUG_DISPLAY', false );
define( 'FS_METHOD', 'direct' );
if ( ! defined( 'ABSPATH' ) ) {
	define( 'ABSPATH', __DIR__ . '/' );
}
require_once ABSPATH . 'wp-settings.php';
PHP
else
	echo "==> wp-config.php already present."
fi

# 5. Install WordPress -------------------------------------------------------
if ! $WP core is-installed >/dev/null 2>&1; then
	echo "==> Installing WordPress..."
	$WP core install \
		--url="$SITE_URL" \
		--title="Ювента — клиника косметологии в Самаре | IUVENTA" \
		--admin_user="${WP_ADMIN_USER:-admin}" \
		--admin_password="${WP_ADMIN_PASSWORD:-admin123}" \
		--admin_email="${WP_ADMIN_EMAIL:-admin@iuventa.local}" \
		--skip-email
else
	echo "==> WordPress already installed."
fi

# 6. Theme + permalinks ------------------------------------------------------
echo "==> Activating IUVENTA theme..."
$WP theme activate iuventa
$WP rewrite structure '/%postname%/' >/dev/null
$WP option update blogname "Ювента — клиника косметологии в Самаре" >/dev/null

echo "==> Done. Start the site with: bin/serve.sh  (http://localhost:8080)"
